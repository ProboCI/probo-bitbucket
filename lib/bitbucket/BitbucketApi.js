'use strict';

const util = require('util');
const request = require('request');

// Bitbucket Cloud rotates refresh tokens (enforced 2026-05-04): every refresh
// invalidates the refresh token that was used. Every request builds its own
// client, so two of them holding the same refresh token must share a single
// refresh, and one that still holds an already-consumed token must be handed
// the pair that replaced it instead of burning the chain with a second call.
// Both maps are process-wide and keyed by the consumed refresh token: the
// callbacks waiting on a refresh in flight, and the {body, at} each produced.
const pendingRefreshes = new Map();
const rotatedTokens = new Map();

// Bitbucket access tokens last two hours; keep a margin so a cached token is
// never handed out moments before it expires.
const DEFAULT_EXPIRES_IN = 7200;
const CACHE_SAFETY_MARGIN_MS = 5 * 60 * 1000;
const ROTATION_RETENTION_MS = 3 * 60 * 60 * 1000;

// A refresh that never answers would otherwise hold pendingRefreshes for its
// refresh token forever, and every later request on that chain would wait on
// it.
const REFRESH_TIMEOUT_MS = 30 * 1000;

/**
 * Handles HTTP requests to Bitbucket API
 */
class BitbucketApi {

  /**
   * @param {Object} config - An object with the following properties:
   * @param {Logger} config.log - logger to use
   * @param {string} config.version - '2.0' - the Bitbucket API version to use. Defaults to '2.0'
   * @param {Object} config.auth - An authorization object:
   * @param {string} config.auth.consumerKey - consumer key for the API (get from BitBucket integration dashboard)
   * @param {string} config.auth.consumerSecret - consumer secret for the API (get from BitBucket integration dashboard)
   * @param {string} config.auth.token - token that was generated by BitBucket for the user (almost certainly this needs to be refreshed, they only last 1 hour for bitbucket.
   * @param {string} config.auth.refreshToken - refresh token that was generated by BitBucket for the user
   * @param {number} [config.auth.tokenCreatedAt] - when the access token was issued, in seconds since the epoch, as the coordinator stores it
   * @param {number} [config.auth.tokenExpiresIn] - the access token's lifetime in seconds. With tokenCreatedAt, a token known to have expired is refreshed before it is ever sent.
   * @param {Function} [config.onTokenRefreshed] - called with (body, previous, meta) whenever this client takes on a new token pair; see refreshToken()
   * @param {number} [config.refreshTimeoutMs] - how long to wait for Bitbucket's token endpoint before giving up
   */
  constructor(config) {
    this.config = config || {};
    this.log = config.log.child({consumerKey: config.auth.consumerKey});
    this.onTokenRefreshed = config.onTokenRefreshed || null;
    this.refreshTimeoutMs = config.refreshTimeoutMs || REFRESH_TIMEOUT_MS;

    // How the access token currently held was obtained: null for the one the
    // caller passed in, else the origin of the refresh that produced it
    // ('refresh', 'pending' or 'cache'). http() uses it to tell a remembered
    // token that turned out to be dead from one Bitbucket just issued.
    this.tokenOrigin = null;

    this.authenticate(config.auth);

    // bind all methods to this so context of this.repos.method is still this.
    let subs = ['repos', 'statuses'];
    let method;

    for (let sub of subs) {
      // make sure we don't bind the prototype function to this!
      let newSub = {};

      for (let m in this[sub]) {
        if (this[sub].hasOwnProperty(m)) {
          method = this[sub][m];
          if (typeof method.bind == 'function') {
            newSub[m] = method.bind(this);
          }
        }
      }

      this[sub] = newSub;
    }
  }

  /**
   * Synchronous call that sets up the HTTP client with the proper auth tokens.
   *
   * @param {Object} auth - An object containing parameters to be sotred in this.auth.
   * @param {String} auth.token - The auth token to include in the headers of new requests.
   */
  authenticate(auth) {
    if (!auth) {
      throw new Error('Bitbucket authentication config missing');
    }

    this.auth = this.utils.defaults(auth, this.auth);

    this.oauth = {
      headers: this.makeAuthHeaders(this.auth.token),
    };
  }

  /**
   * Makes an authenticated request, refreshing the access token when it is
   * known or found to have expired. Every Bitbucket call the handler makes
   * (the webhook's config fetch, build statuses, branch, commit and pull
   * request lookups) goes through here, so expiry is handled in one place and
   * the same way for all of them.
   *
   * A token whose stored timestamps say it has expired is refreshed before
   * the first request. Otherwise a 401, or a token error message under any
   * status, triggers one refresh and one retry. If that refresh handed out a
   * pair remembered from an earlier rotation and Bitbucket rejects that too,
   * one more refresh is forced against Bitbucket before giving up.
   *
   * @param {Object} opts : all standard request call options with the addition of the following (that don't get passed to
   * request):
   * @param {string} opts.method - lowercases HTTP method, with "del" instead of "DELETE" (defaults to "get")
   * @param {string} opts.path (appended to this.url)
   * @param {function} cb - The function to run once the token is refreshed and full http request is complete.
   * @return {Null} - No return value.
   */
  http(opts, cb) {
    const self = this;
    let refreshes = 0;

    function attempt() {
      self._http(opts, function(err, res, body) {
        if (!err || !self.isAuthFailure(err, body)) {
          return cb(err, res, body);
        }

        if (refreshes === 0) {
          return refreshAndRetry(false);
        }

        if (refreshes === 1 && self.tokenOrigin === 'cache') {
          self.log.info('a remembered access token was rejected; refreshing against Bitbucket');
          return refreshAndRetry(true);
        }

        cb(err, res, body);
      });
    }

    function refreshAndRetry(force) {
      refreshes++;
      self.refreshToken({force: force}, function(refreshErr) {
        if (refreshErr) { return cb(refreshErr); }
        attempt();
      });
    }

    if (!self.auth.token || self.isAccessTokenExpired()) {
      return refreshAndRetry(false);
    }

    attempt();
  }

  /**
   * @param {Object} opts : all standard request call options with the addition of the following (that don't get passed to request).
   * @param {string} opts.method - lowercases HTTP method, with "del" instead of "DELETE" (defaults to "get")
   * @param {string} opts.path (appended to this.url)
   * @param {function} cb - The function to run once the http request is complete.
   * @return {Mixed} - The result of the request call.
   */
  _http(opts, cb) {
    opts = opts || {};
    let method = opts.method || 'get';
    let version = opts.version || '2.0';
    let url = `https://api.bitbucket.org/${version}`;

    opts = this.utils.defaults(opts, {
      uri: opts.url || (url + opts.path),
      headers: this.utils.defaults(this.oauth.headers, opts.headers),
      json: true,
    });

    delete opts.version;
    delete opts.url;
    delete opts.method;
    delete opts.path;

    function handler(err, res, body) {
      if (err) return cb(err);

      if (!(res.statusCode >= 200 && res.statusCode < 300)) {
        err = new Error(JSON.stringify(body));
        err.statusCode = res.statusCode;
        err.statusMessage = res.statusMessage;
        err.body = body;

        return cb(err);
      }

      cb(err, res, body);
    }

    return request[method](opts, handler);
  }

  /**
   * Obtains a new access token. The refresh token this instance holds may
   * already have been consumed by another instance in this process, in which
   * case the pair that replaced it is reused rather than requested again.
   *
   * The onTokenRefreshed hook receives (body, previous, meta), where previous
   * is the pair this instance held before and meta.origin says how the new
   * pair was obtained: 'refresh' (this call talked to Bitbucket), 'pending'
   * (joined a refresh already in flight) or 'cache' (reused an earlier
   * rotation). Only 'refresh' needs to be persisted by the caller. meta.at is
   * when the pair was issued, in milliseconds.
   *
   * @param {Object} [opts] - Options.
   * @param {boolean} [opts.force] - Skip a remembered pair and ask Bitbucket,
   *   using the newest refresh token known for the chain. For when the
   *   remembered access token has just been rejected.
   * @param {Function} done - callback(err, body)
   * @return {Null} - No return value.
   */
  refreshToken(opts, done) {
    if (typeof opts === 'function') {
      done = opts;
      opts = {};
    }
    opts = opts || {};

    const previous = {token: this.auth.token, refreshToken: this.auth.refreshToken};

    if (!previous.refreshToken) {
      let err = new Error('Unable to refresh Bitbucket access token: no refresh token available');
      err.reauthorize = true;
      return done(err);
    }

    const resolved = BitbucketApi._resolveRotation(previous.refreshToken);
    if (resolved.body && !opts.force) {
      this.log.debug('reusing the token pair from an earlier refresh of this refresh token');
      this._applyRefreshedTokens(resolved.body, previous, {origin: 'cache', at: resolved.at});
      return done(null, resolved.body);
    }

    // The newest refresh token known for this chain. Usually the one we hold,
    // but a cached rotation whose access token has since expired (or was just
    // rejected) moves us on.
    const key = resolved.refreshToken;

    if (pendingRefreshes.has(key)) {
      this.log.debug('joining a refresh of this refresh token that is already in flight');
      pendingRefreshes.get(key).push((err, body) => {
        if (err) return done(err);
        this._applyRefreshedTokens(body, previous, {origin: 'pending', at: Date.now()});
        done(null, body);
      });
      return;
    }

    pendingRefreshes.set(key, []);
    this.log.info({forced: !!opts.force}, 'refreshing token');

    const finish = (err, body) => {
      const waiters = pendingRefreshes.get(key) || [];
      pendingRefreshes.delete(key);

      if (!err) {
        BitbucketApi._rememberRotation(key, body);
        this._applyRefreshedTokens(body, previous, {origin: 'refresh', at: Date.now()});
      }

      done(err, body);
      waiters.forEach((waiter) => waiter(err, body));
    };

    let requestOptions = {
      uri: 'https://bitbucket.org/site/oauth2/access_token',
      form: {
        grant_type: 'refresh_token',
        refresh_token: key,
      },
      auth: {
        user: this.auth.consumerKey,
        pass: this.auth.consumerSecret,
      },
      json: true,
      timeout: this.refreshTimeoutMs,
    };

    request.post(requestOptions, (error, response, body) => {
      if (error) {
        const timedOut = error.code === 'ETIMEDOUT' || error.code === 'ESOCKETTIMEDOUT' ||
          /E(SOCKET)?TIMEDOUT/.test(error.message || '');
        let transportError = new Error('Unable to refresh Bitbucket access token: ' +
          (timedOut ? `no answer from Bitbucket within ${this.refreshTimeoutMs}ms` : error.message));
        transportError.cause = error;
        // Nothing says the refresh token is dead; the caller may try again.
        transportError.reauthorize = false;

        this.log.error({err: error, timedOut: timedOut}, 'Bitbucket token refresh failed');

        return finish(transportError);
      }

      // A rejected refresh token comes back as a 400 with an error body, not as
      // a transport error. Bail out before touching this.auth: an undefined
      // access token would silently restore the old expired one (see
      // utils.defaults), and persisting it would wipe the stored credentials.
      if (!body || !body.access_token) {
        let reason = (body && (body.error_description || body.error)) || `HTTP ${response.statusCode}`;
        let refreshError = new Error(`Unable to refresh Bitbucket access token: ${reason}`);
        refreshError.statusCode = response.statusCode;
        refreshError.body = body;
        // The refresh token itself is dead: retrying can't help, the user has
        // to re-authorize. Bitbucket reports a rotated-away token as
        // unauthorized_client ("refresh_token is invalid") and a revoked or
        // expired one as invalid_grant.
        refreshError.reauthorize = BitbucketApi.isDeadRefreshToken(body);

        this.log.error({err: refreshError, statusCode: response.statusCode}, 'Bitbucket token refresh failed');

        return finish(refreshError);
      }

      this.log.debug('refreshed auth token from BB');
      finish(null, body);
    });
  }

  /**
   * Swaps the new pair into this instance and tells the owner about it.
   *
   * @param {Object} body - The token response from Bitbucket.
   * @param {Object} previous - The {token, refreshToken} pair held before.
   * @param {Object} meta - {origin, at} describing how and when the pair was obtained.
   * @return {Null} - No return value.
   */
  _applyRefreshedTokens(body, previous, meta) {
    meta = meta || {};
    const issuedAtMs = meta.at || Date.now();

    // Bitbucket only returns refresh_token when it rotates one, so keep ours
    // otherwise. The timestamps let isAccessTokenExpired() judge this token
    // rather than the one it replaced.
    this.authenticate({
      token: body.access_token,
      refreshToken: body.refresh_token || previous.refreshToken,
      tokenCreatedAt: Math.floor(issuedAtMs / 1000),
      tokenExpiresIn: body.expires_in || DEFAULT_EXPIRES_IN,
    });
    this.tokenOrigin = meta.origin || 'refresh';

    if (this.onTokenRefreshed) {
      this.onTokenRefreshed(body, previous, meta);
    }
  }

  /**
   * Follows the chain of remembered rotations from a refresh token to the
   * newest pair issued for it.
   *
   * @param {string} refreshToken - The refresh token an instance holds.
   * @return {Object} - {refreshToken, body, at}: the newest refresh token on
   *   the chain, the newest pair if its access token is still usable (else
   *   null), and when that pair was issued in milliseconds.
   */
  static _resolveRotation(refreshToken) {
    let current = refreshToken;
    let latest = null;
    const seen = new Set();

    while (rotatedTokens.has(current) && !seen.has(current)) {
      seen.add(current);
      latest = rotatedTokens.get(current);
      if (!latest.body.refresh_token || latest.body.refresh_token === current) {
        break;
      }
      current = latest.body.refresh_token;
    }

    if (!latest) {
      return {refreshToken: current, body: null, at: null};
    }

    const lifetimeMs = (latest.body.expires_in || DEFAULT_EXPIRES_IN) * 1000;
    const usable = (Date.now() - latest.at) < (lifetimeMs - CACHE_SAFETY_MARGIN_MS);

    return {refreshToken: current, body: usable ? latest.body : null, at: latest.at};
  }

  static _rememberRotation(refreshToken, body) {
    const now = Date.now();

    rotatedTokens.forEach((entry, key) => {
      if (now - entry.at > ROTATION_RETENTION_MS) {
        rotatedTokens.delete(key);
      }
    });

    rotatedTokens.set(refreshToken, {body, at: now});
  }

  /**
   * Forgets every remembered rotation and in-flight refresh. For tests.
   *
   * @return {Null} - No return value.
   */
  static resetRefreshState() {
    pendingRefreshes.clear();
    rotatedTokens.clear();
  }

  /**
   * @param {Object} body - The error body from the token endpoint.
   * @return {boolean} - Whether the refresh token can never work again.
   */
  static isDeadRefreshToken(body) {
    if (!body || !body.error) return false;

    if (body.error === 'invalid_grant' || body.error === 'unauthorized_client') {
      return true;
    }

    // A refresh token Bitbucket never issued to this consumer, or has since
    // forgotten (unused for three months), comes back as invalid_request
    // "Invalid refresh_token". Retrying can't help with that either.
    return body.error === 'invalid_request' && /refresh_token/i.test(body.error_description || '');
  }

  /**
   * Whether an error body from the API says the access token is no good.
   *
   * Bitbucket has shipped several wordings: 'Access token expired...',
   * 'OAuth2 access token expired...' and, since its 2026 OAuth changes,
   * 'Token is invalid, expired, or not supported for this endpoint.'. Match
   * on a token being expired or invalid rather than on one sentence, so the
   * next rewording does not stop every path from refreshing again.
   *
   * @param {Object} body - The error body.
   * @return {boolean} - True when the token should be refreshed.
   */
  isTokenError(body) {
    let message = body && body.error && body.error.message;

    if (!message || typeof message !== 'string') return false;

    return /\btoken\b[^.]*\b(expired|invalid)\b/i.test(message) ||
      /\b(expired|invalid)\b[^.]*\btoken\b/i.test(message);
  }

  /**
   * @param {Error} err - The error _http() produced.
   * @param {*} body - The response body, if any.
   * @return {boolean} - Whether the request failed because of the access token.
   */
  isAuthFailure(err, body) {
    if (!err) return false;
    if (err.statusCode === 401) return true;

    return this.isTokenError(err.body || body);
  }

  /**
   * Whether the stored timestamps say the access token has run out. Without
   * timestamps nothing is known, and the token is tried.
   *
   * @return {boolean} - True when the token is past, or within five minutes
   *   of, the end of its lifetime.
   */
  isAccessTokenExpired() {
    const createdAt = Number(this.auth.tokenCreatedAt);
    const expiresIn = Number(this.auth.tokenExpiresIn);

    if (!createdAt || !expiresIn) return false;

    // Stored in seconds by the coordinator; tolerate milliseconds too.
    const createdAtMs = createdAt > 1e12 ? createdAt : createdAt * 1000;

    return Date.now() >= createdAtMs + expiresIn * 1000 - CACHE_SAFETY_MARGIN_MS;
  }

  makeAuthHeaders(token) {
    return {
      authorization: `Bearer ${token}`,
    };
  }
}

BitbucketApi.prototype.repos = {

  /**
   * Gets the list of branches for a Bitbucket repo.
   *
   * @param {Object} opts
   * @param {string} opts.owner - The repo owner/workspace.
   * @param {string} opts.repo - The repo slug.
   * @param {Function} cb - callback(err, branches)
   */
  getBranches: function(opts, cb) {
    let allBranches = [];

    const fetchPage = (url) => {
      let params = url ? {url} : {
        method: 'get',
        path: `/repositories/${opts.owner}/${opts.repo}/refs/branches?pagelen=100`,
      };

      this.http(params, function(err, res, body) {
        if (err) return cb(err);

        let branches = (body.values || []).map(b => ({
          name: b.name,
          sha: b.target.hash,
        }));

        allBranches = allBranches.concat(branches);

        if (body.next) {
          fetchPage(body.next);
        } else {
          cb(null, allBranches);
        }
      });
    };

    fetchPage(null);
  },

  /**
   * Gets the list of commits for a Bitbucket repo, optionally filtered by branch/sha.
   *
   * @param {Object} opts
   * @param {string} opts.owner - The repo owner/workspace.
   * @param {string} opts.repo - The repo slug.
   * @param {string} [opts.sha] - Branch name or commit SHA to filter by (optional).
   * @param {Function} cb - callback(err, commits)
   */
  listCommits: function(opts, cb) {
    let allCommits = [];
    let path = `/repositories/${opts.owner}/${opts.repo}/commits`;
    if (opts.sha) path += `/${opts.sha}`;
    path += '?pagelen=30';

    const fetchPage = (url) => {
      let params = url ? {url} : {method: 'get', path};

      this.http(params, function(err, res, body) {
        if (err) return cb(err);

        let commits = (body.values || []).map(c => ({
          sha: c.hash,
          message: c.message,
          author: c.author.user ? (c.author.user.display_name || c.author.user.nickname) : c.author.raw,
          date: c.date,
          url: c.links.html.href,
        }));

        allCommits = allCommits.concat(commits);

        // Only fetch first page (30 commits) — same as GitHub's default page
        cb(null, allCommits);
      });
    };

    fetchPage(null);
  },

  /**
   * Gets information on a commit.
   */
  getCommit: function(opts, cb) {
    let required = [
      'owner',
      'repo',
      'ref',
    ];
    for (let field of required) {
      if (!opts.hasOwnProperty(field)) {
        return cb(new Error(`${field} is required when calling getPullRequest`));
      }
    }

    let params = {
      method: 'get',
      path: `/repositories/${opts.owner}/${opts.repo}/commit/${opts.ref}`
    };

    this.log.debug({params}, `Getting commit ${opts.owner}/${opts.repo} #${opts.ref}`);

    this.http(params, function(err, res, body) {
      if (err) return cb(err);

      cb(null, body);
    });
  },

  /**
   * Gets the status of a bitbucket pull request.
   */
  getPullRequest: function(opts, cb) {
    if (typeof opts == 'function') {
      cb = opts;
      opts = {};
    }
    let required = [
      'owner',
      'repo',
      'id',
    ];
    for (let field of required) {
      if (!opts.hasOwnProperty(field)) {
        return cb(new Error(`${field} is required when calling getPullRequest`));
      }
    }
    let params = {
      method: 'get',
      path: `/repositories/${opts.owner}/${opts.repo}/pullrequests/${opts.id}`,
    };
    this.log.debug({params}, `Getting PR ${opts.owner}/${opts.repo} #${opts.id}`);

    this.http(params, function(err, res, body) {
      if (err) return cb(err);

      cb(err, body);
    });
  },

  /**
   * Gets content of files (path specified) or directories (no path)
   *
   * @param {Object} opts - A hash containing configuration options.
   * @param {String} opts.accountName - The name of the account to retrieve data for.
   * @param {String} opts.repositorySlug - The name of the repository.
   * @param {String} opts.path - The path of the file to retrieve.
   * @param {object} [opts.at] - commit sha (alias), if not specified, opts.ref will be used
   * @param {object} [opts.path] - path of the file to get within the repo. if empty or not specified, returns directory listing at root.
   * @param {Function} cb - The calback function to call when the content has been retrieved.
   * @return {Null} - No return value.
   */
  getContent: function(opts, cb) {
    if (typeof opts == 'function') {
      cb = opts;
      opts = {};
    }

    if (!opts.accountName) {
      return cb(new Error('getContent accountName required'));
    }
    if (!opts.repositorySlug) {
      return cb(new Error('getContent repositorySlug required'));
    }

    opts.path = opts.path || '';
    opts.ref = opts.at || opts.ref;
    var path = `/repositories/${opts.accountName}/${opts.repositorySlug}/src/${opts.ref}/${opts.path}?pagelen=100`;

    delete opts.path;
    delete opts.at;
    delete opts.ref;

    var params = {
      path,
    };

    this.http(params, function(err, res, content) {
      if (err) return cb(err);

      if (content.data) {
        // getting contents of a file
        content = content.data;
      }
      else if (content.path) {
        content = content.files;
      }
      else if (content.values) {
        content = content.values;
      }
      cb(err, content);
    });
  },
};

BitbucketApi.prototype.statuses = {
  create: function(status, opts, cb) {
    if (typeof opts == 'function') {
      cb = opts;
      opts = {};
    }

    // validate status
    if (!status) {
      return cb(new Error('statuses.create status required'));
    }

    let requiredStatusFields = ['state', 'key', 'url'];
    let field;
    for (field of requiredStatusFields) {
      if (!status[field]) {
        return cb(new Error(`statuses.create status.${field} required`));
      }
    }

    // automatically uppcase state
    status.state = status.state.toUpperCase();
    let validStates = ['SUCCESSFUL', 'FAILED', 'INPROGRESS'];
    if (validStates.indexOf(status.state) < 0) {
      return cb(new Error(`statuses.create status. ${field} required to be one of ` + ['SUCCESSFUL', 'FAILED', 'INPROGRESS'].join(', ')));
    }

    // validate opts
    if (!opts.commitId && !opts.ref) {
      return cb(new Error('statuses.create commitId or ref config required'));
    }

    let ref = opts.commitId || opts.ref;
    let path = util.format('/repositories/%s/commit/%s/statuses/build',
                           opts.slug, ref);

    delete opts.commitId;
    delete opts.ref;
    delete opts.slug;

    let params = this.utils.defaults(opts, {
      path: path,
      method: 'post',
      body: status,
      json: true,
    });

    this.http(params, function(err, res, content) {
      if (err) return cb(err);

      if (content && content.errors) {
        return cb(new Error(content.errors[0].message));
      }
      cb(err, content);
    });
  },
};

BitbucketApi.prototype.utils = {
  extend: function(dest, src) {
    dest = dest || {};
    src = src || {};

    let ret = {};

    for (let x in dest) {
      if (dest.hasOwnProperty(x)) {
        ret[x] = dest[x];
      }
    }

    for (let x in src) {
      if (src.hasOwnProperty(x)) {
        ret[x] = src[x];
      }
    }

    return ret;
  },

  defaults: function(dest, src) {
    dest = dest || {};
    src = src || {};

    let ret = {};

    for (let x in dest) {
      if (dest.hasOwnProperty(x)) {
        ret[x] = dest[x];
      }
    }

    for (let x in src) {
      if (src.hasOwnProperty(x) && typeof dest[x] == 'undefined') {
        ret[x] = src[x];
      }
    }

    return ret;
  },
};

BitbucketApi.DEFAULT_EXPIRES_IN = DEFAULT_EXPIRES_IN;

